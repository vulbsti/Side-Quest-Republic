import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const code=await readFile(new URL('./dist/interactions.js',import.meta.url),'utf8');
const {buildInteractionCandidates:build}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const ravi={id:'ravi',name:'RAVI · CHAI',x:-21,z:27};
const speaker={id:'speaker',name:'Ravi’s speaker',type:'speaker',x:-19.5,z:26,model:{visible:true}};
const input={player:{x:-20,z:26},items:[speaker],npcs:[ravi],game:{speakerBorrowed:true}};
assert.equal(build(input)[0].id,'item:speaker','borrowed speaker must beat nearby Ravi talk');
assert.equal(build({...input,game:{}})[0].id,'permission:speaker');
assert.ok(!build({...input,game:{}}).some(c=>c.type==='item'),'permission before pickup');
const stage={...speaker,x:-3,z:-11.5,on:true};
let list=build({player:{x:-2,z:-11},items:[stage],npcs:[{id:'mira',name:'MIRA',x:-2,z:-10}],game:{speakerBorrowed:true,speakerDelivered:true,crowd:3}});
assert.equal(list[0].type,'performance');
list=build({player:{x:-2,z:-11},items:[stage],game:{speakerBorrowed:true,speakerDelivered:true,performance:true}});
assert.equal(list[0].type,'item','finished gig offers speaker retrieval');
assert.ok(list.some(c=>c.type==='performance'),'encore remains cycleable');
assert.equal(build({...input,game:{carrying:speaker,performance:true}})[0].id,'return:speaker:ravi');
assert.ok(!build({player:{x:0,z:0},game:{carrying:{type:'key'}}}).some(c=>c.type==='returnkey'));
assert.equal(build({player:{x:28,z:0},game:{carrying:{type:'key'}}})[0].type,'returnkey');
assert.equal(build({player:{x:0,z:0},npcs:[{id:'officer',name:'SHARMA',x:1,z:0}],game:{carrying:{type:'key'}}})[0].type,'returnkey');
assert.ok(!build({player:{x:0,z:-11},game:{speakerDelivered:true}}).some(c=>c.type==='performance'),'absent speaker cannot play gig');
const water=build({player:{x:0,z:0},npcs:[{id:'sana',name:'SANA',x:1,z:0}],game:{carrying:{type:'water'}}});
assert.equal(water[0].id,'water:sana');
assert.equal(build({player:{x:0,z:-11},game:{carrying:speaker}})[0].type,'stage');
const before=JSON.stringify(input);const a=build(input),b=build({...input,npcs:[...input.npcs].reverse()});
assert.deepEqual(a.map(c=>c.id),b.map(c=>c.id));assert.equal(JSON.stringify(input),before,'candidate builder must be pure');
assert.equal(new Set(list.map(c=>c.id)).size,list.length);
console.log('Interaction candidate tests passed');
