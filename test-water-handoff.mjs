import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync('dist/main.js','utf8');
const start=source.indexOf('function interactNPC('),end=source.indexOf('\nfunction ',start+1);
let saves=0,begins=0;
const c={game:{carrying:{type:'water'},waterStock:2,water:0,crowd:0},sim:{trust:0,heat:10},day:{available:()=>[{actorId:'sana'}],distance:()=>1,begin:()=>begins++,state:{actors:{sana:{activity:'help'}}}},say(){},sound:{sfx(){}},toast(){},memory(){},checkpoint(){saves++;}};
vm.createContext(c);vm.runInContext(source.slice(start,end),c);
const sana={id:'sana',livingActor:true,dayActor:true};c.interactNPC(sana);
assert.equal(c.game.waterStock,1);assert.equal(c.game.water,1);assert.equal(c.sim.trust,8);assert.equal(sana.thanks,true);assert.equal(sana.trust,1);assert.equal(begins,0,'carried water is delivered before a new dialogue');assert.equal(saves,1,'handoff immediately survives a save');
c.interactNPC(sana);assert.equal(c.game.waterStock,1);assert.equal(c.sim.trust,8);assert.equal(begins,1,'already served person can resume their encounter');
const busy={id:'busy',incidentOrder:{objective:'scatter'}};c.interactNPC(busy);assert.equal(c.game.waterStock,1,'active incident is not interrupted');
c.game.waterStock=0;c.interactNPC({id:'friend'});assert.equal(c.game.water,1,'empty crate cannot give water');
console.log('PASS water handoff reaches named actors, persists once, respects incidents and stock');
