// The map: one page that says what the game is made of and what a player can actually reach.
// Generated from the engine, the content and the latest verify run (verify/map.md). Read this before
// changing the game; diff it after.
import { E, META, CONTENT } from './engine.mjs';
import { INVARIANTS } from './properties.mjs';
import { ROUTES } from './seeds.mjs';

const routeExpects = (rid, what) => ROUTES[rid]?.expects.includes(what);
const esc = (t) => String(t ?? '').replace(/\|/g, '/').replace(/\n/g, ' ');
const cut = (t, n = 90) => (t.length > n ? t.slice(0, n - 1) + '…' : t);
const spotName = (p) => [...Object.entries(E.WAYPOINTS), ...Object.entries(E.SPOTS)].find(([, w]) => p && Math.abs(w.x - p.x) < 0.01 && Math.abs(w.z - p.z) < 0.01)?.[0];

/** A plan in words: "11:05 take key, walk to metro, ...". */
export function describePlan(plan, max = 8) {
  const words = [];
  for (const op of plan) {
    if (op.op === 'until') words.push(op.clock);
    else if (op.op === 'wait') words.push(`wait ${Math.round(op.s / E.SECONDS_PER_MINUTE)} min`);
    else if (op.op === 'go' && !op.follow) words.push(`walk to ${spotName(op.to) ?? `${op.to.x.toFixed(0)},${op.to.z.toFixed(0)}`}`);
    else if (op.op === 'act') {
      const c = op.cmd;
      words.push([c.type, c.object, c.to, c.rumour, c.how, c.stance].filter(Boolean).join(' '));
    }
  }
  if (!words.length) return 'do nothing';
  return words.length > max ? words.slice(0, max).join(', ') + `, … (${words.length} steps)` : words.join(', ');
}

export function buildMap(report) {
  const W = report.witness, cov = report.coverage;
  const L = [];
  L.push('# Game map', '');
  L.push('Generated by `npm run verify` from the engine, `dist/loop/content.js` and the latest exploration. Do not edit by hand.', '');
  L.push(`**Reachable by a player:** ${cov.ending.reached}/${cov.ending.of} endings, ${cov.rule.reached}/${cov.rule.of} rules, ${cov.link.reached}/${cov.link.of} board links fire, ${cov.board.reached}/${cov.board.of} can be learned (the player hears them). `
    + `**Intended routes that work:** ${Object.values(report.intents).filter((i) => i.ok).length}/${Object.keys(report.intents).length}. `
    + `**Verbs that change an outcome:** ${Object.values(report.agency).filter((a) => a.changes).length}/12.`, '');
  L.push('A "witness" is the shortest plan the checker found that reaches the item; every ending\'s witness is in `verify/traces/` and plays in the game: serve the repo root and open `/dist/index.html?replay=/verify/traces/<file>` (see `verify/README.md`).', '');

  L.push('## Endings', '', '| Ending | Title | Reached by | Intended route |', '|---|---|---|---|');
  for (const id of META.endings) {
    const routes = Object.entries(report.intents).filter(([rid]) => routeExpects(rid, `ending:${id}`));
    const routeText = routes.map(([rid, v]) => `${rid}: ${v.ok ? 'works' : '**broken**'}`).join('; ') || '—';
    L.push(`| \`${id}\` | ${esc(CONTENT.ENDINGS[id].title)} | ${W.ending[id] ? esc(describePlan(W.ending[id].plan)) : '**unreached**'} | ${routeText} |`);
  }

  L.push('', '## Intended routes', '', 'Designer claims from `verify/seeds.mjs`, played the way a player can (walking, real witnesses).', '', '| Route | Status | Why |', '|---|---|---|');
  for (const [id, v] of Object.entries(report.intents)) L.push(`| ${id} | ${v.ok ? 'works' : '**broken**'} | ${v.ok ? '' : esc(`missing ${v.missing.join(', ')}. ${v.why.join('; ')}`)} |`);

  L.push('', '## Rules', '', 'Each rule is "when X happens, Y does Z" and must say something visible.', '', '| Rule | What the player sees | Reached by |', '|---|---|---|');
  for (const r of E.RULES) {
    const line = CONTENT.LINES[r.says]?.[0]?.[1] ?? `(no line for ${r.says})`;
    L.push(`| \`${r.id}\` | ${esc(cut(line))} | ${W.rule[r.id] ? esc(describePlan(W.rule[r.id].plan, 5)) : '**unreached**'} |`);
  }

  L.push('', '## Cause and effect (chaos board links)', '', '```mermaid', 'flowchart LR');
  const node = new Map();
  const id = (t) => { if (!node.has(t)) node.set(t, `n${node.size}`); return node.get(t); };
  for (const [lid, l] of Object.entries(CONTENT.LINKS)) {
    const reached = !!W.link[lid];
    L.push(`  ${id(l.from)}["${esc(cut(l.from, 40)).replace(/"/g, "'")}"] ${reached ? '-->' : '-.->'}|${lid}| ${id(l.to)}["${esc(cut(l.to, 40)).replace(/"/g, "'")}"]`);
  }
  L.push('```', '', 'Dotted arrows are links no explored day reached.', '');
  const unheard = META.links.filter((l) => W.link[l] && !W.board[l]);
  if (unheard.length) L.push(`Links that fire but that no explored player was close enough to hear (so the board never learns them): ${unheard.map((l) => `\`${l}\``).join(', ')}.`, '');
  const unreached = META.links.filter((l) => !W.link[l]);
  if (unreached.length) L.push(`Unreached links: ${unreached.map((l) => `\`${l}\``).join(', ')}.`, '');

  L.push('## Verbs', '', '| Verb | Changes an outcome? |', '|---|---|');
  for (const v of ['take', 'give', 'drop', 'talk', 'whisper', 'pester', 'rally', 'film', 'stance', 'provocateur', 'scene', 'plead']) {
    const a = report.agency[v];
    L.push(`| ${v} | ${a?.changes ? `yes: ${esc(a.changes)}` : a ? `not found (${a.tried} tried)` : 'never used by the explorer'} |`);
  }

  L.push('', '## Properties checked', '', `Invariants (every simulated second): ${Object.keys(INVARIANTS).map((n) => `\`${n}\``).join(', ')}.`, '',
    'Every day: it ends by 18:00 with a card; no rule is silent (its line appears within 5 clock minutes); chases end within 20 clock minutes; the card only cites causes that came first.', '',
    'Every run: no hidden state (plans and traces replay to identical days, in any order, at either tempo); an idle day still escalates; the idle day ends the same at slice and `?long` tempo.', '',
    `Pacing (reported, not enforced): worst dead air near the player ${report.pacing.worstDeadAirMin} clock min; idle day ${report.pacing.idleDayDeadAirMin}.`, '');
  return L.join('\n');
}

