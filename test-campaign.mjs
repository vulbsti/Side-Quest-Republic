import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const code=await readFile(new URL('./dist/campaign.js',import.meta.url),'utf8');
const {campaignSummary:s}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
assert.equal(s().completed,0);assert.equal(s().total,3);assert.equal(s().allComplete,false);
const incomplete={performance:true,buddyComplete:true,adviceComplete:true};
assert.equal(s(incomplete).completed,2,'performance alone does not close borrowed-speaker story');
assert.equal(s({...incomplete,speakerReturned:true}).allComplete,true);
assert.ok(s({...incomplete,speakerReturned:true}).recap[0].includes('Sab ka kaam poora'));
assert.ok(s(incomplete).recap.some(t=>t.includes('waiting')));
assert.notEqual(s({keyTaken:true}).endingTitle,s({keyTaken:true,keyReturned:true}).endingTitle);
assert.equal(s({}, {mischief:40}).endingTitle,'A LOCAL INCIDENT.');
assert.equal(s({...incomplete,speakerReturned:true},{trust:50}).endingTitle,'CHAOTIC. RELIABLE.');
const g={water:3,photos:['a','b','c'],keyReturned:true,memories:[{title:'Captain Pending Results'},{title:'Crowd ne saath diya'}],social:{history:{a:{count:1},b:{count:1},c:{count:2},d:{count:1}}}};
const original=JSON.stringify(g),r=s(g,{escaped:1});
for(const id of ['water','photos','key','costume','slogan','escape','social'])assert.equal(r.badges.find(b=>b.id===id).done,true,id);
assert.equal(s({social:{history:{a:{count:100}}}}).badges.find(b=>b.id==='social').done,false,'repeated joke is not four distinct interactions');
assert.equal(JSON.stringify(g),original);
console.log('Campaign summary tests passed');
