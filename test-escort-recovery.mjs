import assert from 'node:assert/strict';
import {createLivingWorld,summarizeWorld,serializeWorld,restoreWorld,advanceWorld,completedEscortReceipts} from './dist/living-world.js';
import {playerParticipationHTML} from './dist/day-client.js';
const world=createLivingWorld(15426,[]);
world.crisisTasks={history:[{id:'escort-1',type:'escort-started',actorId:'crowd1',time:10}]};
assert.equal(summarizeWorld(world).recovery.care,false,'Acceptance does not count as performed care');
assert.deepEqual(completedEscortReceipts(world),[]);
const completed={id:'escort-2',type:'escort-completed',actorId:'crowd1',time:20,description:'Both reach the chai cart. <script>bad</script>'};
world.crisisTasks.history.push(completed,completed);
const result=summarizeWorld(world);
assert.equal(result.recovery.care,true);
assert.equal(result.recovery.medicalPassage,false);
assert.equal(result.recovery.contactsChecked,false);
assert.equal(result.recovery.receipts.filter(r=>r.action==='companion-escort').length,1,'Duplicate receipt id counts once');
assert.equal(result.played,0,'Physical completion does not invent a story choice');
assert.match(result.recap,/physically accompanied/);
assert.doesNotMatch(result.recap,/No performed care/);
const html=playerParticipationHTML([],result);
assert.match(html,/Walked someone/);assert.doesNotMatch(html,/without intervening|<script>/);assert.match(html,/&lt;script&gt;/);
assert.match(playerParticipationHTML([{title:'Earlier story',choice:'A choice'}],result),/Earlier story/);
const restored=restoreWorld(serializeWorld(world));assert.ok(restored);
assert.deepEqual(completedEscortReceipts(restored),completedEscortReceipts(world));
advanceWorld(restored,1200);
assert.equal(restored.ending.recovery.care,true);assert.equal(restored.ending.recovery.medicalPassage,false);
assert.equal(restored.ending.recovery.receipts.filter(r=>r.action==='companion-escort').length,1);
assert.equal(restoreWorld(serializeWorld(restored)).ending.recovery.care,true);
console.log('Escort recovery: accepted versus completed, deduplication, truthful recap, escaped participation and finished save passed');
